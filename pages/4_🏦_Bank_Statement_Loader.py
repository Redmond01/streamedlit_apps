from __future__ import annotations

import streamlit as st
import openpyxl

from core.pos_recon.bank_loader import load_json_to_workbook, load_multiple_json_to_workbook, parse_json_input, infer_date
from core.pos_recon.common import find_report_blocks
from core.memory import get_memory_usage_mb
from utils.audit_viewer import render_audit_table
from utils.ui_components import (
    render_download_button,
    render_header,
    render_memory_badge,
    render_metric_cards,
)

try:
    st.set_page_config(
        page_title="Bank Statement Loader | POS Automation",
        page_icon="🏦",
        layout="wide",
    )
except Exception:
    pass

render_memory_badge()

render_header(
    title="Bank Statement POS Loader",
    subtitle="Load Chrome extension POS JSON export into the BANK STATEMENT column with error annotations",
    icon="🏦",
)

col_intro, col_toggle = st.columns([3, 1])
with col_intro:
    st.markdown(
        """
        Upload your **Reconciliation Workbook** and the **JSON export(s)** generated by the Moniepoint POS Chrome extension. 
        The engine maps credit amounts into the `BANK STATEMENT` column and annotates non-OK/failed records with cell comments.
        """
    )
with col_toggle:
    multi_mode = st.toggle(
        "📑 Multi-Day Loading",
        value=False,
        help="Toggle ON to load multiple JSON exports across multiple workbook blocks in a single pass.",
    )

# -------------------------------------------------------------
# MODE 1: SINGLE-DAY LOADING
# -------------------------------------------------------------
if not multi_mode:
    with st.form("single_bank_loader_form"):
        col1, col2 = st.columns(2)

        with col1:
            st.subheader("1. Reconciliation Workbook & JSON Export")
            workbook_file = st.file_uploader(
                "Upload Reconciliation Workbook (.xlsx / .xlsm)",
                type=["xlsx", "xlsm"],
                help="Excel workbook containing BANK STATEMENT columns.",
            )
            json_file = st.file_uploader(
                "Upload Chrome Extension JSON Export (.json)",
                type=["json"],
                help="The JSON export file from the Chrome extension.",
            )

        with col2:
            st.subheader("2. Loading Parameters")
            date_input = st.text_input(
                "Target Report Date (YYYY-MM-DD)",
                value="",
                placeholder="e.g. 2026-09-19 (leave blank to infer from JSON)",
                help="Selects the matching report block. If blank, infers date from JSON metadata.",
            )
            block_number = st.number_input(
                "Report Block Number",
                min_value=1,
                value=1,
                help="1-based report block number if date is omitted and multiple blocks exist.",
            )
            failed_text = st.text_input(
                "Text for Failed / Non-OK Records",
                value="FAILED",
                help="Value written into the cell for failed records (error details are added as comments).",
            )
            remap_ags10 = st.toggle(
                "🔄 Map AGS 10 to SGR 10",
                value=True,
                help="When enabled (default), terminal AGS 10 (Igbesa AGS) is automatically mapped to SGR 10.",
            )

        submit_button = st.form_submit_button("💳 Populate Bank Statement Column", type="primary", use_container_width=True)

    if submit_button:
        if not workbook_file:
            st.error("Please upload the Reconciliation Workbook.")
        elif not json_file:
            st.error("Please upload the POS Extension JSON export.")
        else:
            date_clean = date_input.strip() or None

            try:
                with st.spinner("Mapping POS records and populating BANK STATEMENT column..."):
                    output_path, stats = load_json_to_workbook(
                        workbook_input=workbook_file,
                        json_input=json_file,
                        date=date_clean,
                        block_number=int(block_number),
                        failed_text=failed_text.strip() or "FAILED",
                        remap_ags10=remap_ags10,
                    )

                st.success(f"Bank statement populated successfully for Report Date: **{stats['workbookDate'] or 'N/A'}**.")

                # Summary Metrics
                render_metric_cards([
                    ("JSON Records", stats["jsonRecords"], None),
                    ("Matched Rows", stats["matched"], None),
                    ("OK Written", stats["okWritten"], None),
                    ("Failed / Status Written", stats["statusWritten"], None),
                ])

                # Download Action
                st.markdown("### 📥 Download Updated Workbook")
                render_download_button(
                    file_path=output_path,
                    label="📥 Download Filled Reconciliation Workbook (.xlsx)",
                    download_filename=f"{workbook_file.name.rsplit('.', 1)[0]}_bank_loaded_{stats['workbookDate'].replace('-', '') if stats['workbookDate'] else 'updated'}.xlsx",
                )

                # Details
                if stats.get("mappingDetails"):
                    render_audit_table(stats["mappingDetails"], title="Terminal Mapping Status Preview")

            except Exception as exc:
                st.error(f"Loader Error: {exc}")

# -------------------------------------------------------------
# MODE 2: MULTI-DAY LOADING
# -------------------------------------------------------------
else:
    st.subheader("1. Upload Target Workbook & Multiple JSON Files")
    col_w, col_j = st.columns(2)

    with col_w:
        workbook_file = st.file_uploader(
            "Upload Reconciliation Workbook (.xlsx / .xlsm)",
            type=["xlsx", "xlsm"],
            key="multi_wb_uploader",
            help="Master reconciliation workbook containing multiple daily report blocks.",
        )

    with col_j:
        json_files = st.file_uploader(
            "Upload Chrome Extension JSON Exports (.json)",
            type=["json"],
            accept_multiple_files=True,
            key="multi_json_uploader",
            help="Select multiple IndexedDB JSON files (e.g. Day 8, Day 9, Day 10...).",
        )

    # Peek available blocks from workbook if uploaded
    available_blocks: list[dict[str, Any]] = []
    if workbook_file:
        try:
            wb_peek = openpyxl.load_workbook(workbook_file, data_only=True)
            ws_peek = wb_peek.active
            available_blocks = find_report_blocks(ws_peek)
            wb_peek.close()
            workbook_file.seek(0)
        except Exception:
            available_blocks = []

    if available_blocks:
        with st.expander(f"ℹ️ Detected {len(available_blocks)} Report Blocks in Workbook", expanded=False):
            block_summary = [
                {
                    "Block #": i + 1,
                    "Date in Row 1": b.get("date") or "(No Date)",
                    "Terminal Col": b["terminal_col"],
                    "Bank Statement Col": b["bank_col"],
                }
                for i, b in enumerate(available_blocks)
            ]
            st.dataframe(block_summary, use_container_width=True)

    if json_files:
        st.subheader("2. Multi-Day Loading Plan")
        st.caption("Verify and configure the Date and Target Block Number for each JSON export:")

        # Container table for each file configuration
        plan_configs = []
        for idx, jfile in enumerate(json_files, 1):
            # Parse records once to infer date and record count
            inferred_date = ""
            rec_count = 0
            try:
                records = parse_json_input(jfile)
                rec_count = len(records)
                inferred_date = infer_date(records) or ""
            except Exception:
                pass

            # Auto-suggest block number if matched by date or sequential index
            auto_block_num = idx
            if available_blocks and inferred_date:
                matched_idx = next(
                    (i + 1 for i, b in enumerate(available_blocks) if b.get("date") == inferred_date),
                    None,
                )
                if matched_idx is not None:
                    auto_block_num = matched_idx

            c_idx, c_file, c_date, c_block = st.columns([0.6, 2.5, 1.5, 1.2])
            with c_idx:
                st.write(f"**#{idx}**")
            with c_file:
                st.markdown(f"**`{jfile.name}`**")
                st.caption(f"{rec_count:,} records found")
            with c_date:
                item_date = st.text_input(
                    f"Date (YYYY-MM-DD)",
                    value=inferred_date,
                    key=f"m_date_{idx}",
                    placeholder="YYYY-MM-DD",
                    label_visibility="collapsed",
                )
            with c_block:
                item_block = st.number_input(
                    f"Block #",
                    min_value=1,
                    value=auto_block_num,
                    key=f"m_block_{idx}",
                    label_visibility="collapsed",
                )

            plan_configs.append({
                "index": idx,
                "json_input": jfile,
                "filename": jfile.name,
                "date": item_date.strip() or None,
                "block_number": int(item_block),
            })

        st.subheader("3. Execution Settings")
        c_set1, c_set2 = st.columns(2)
        with c_set1:
            failed_text = st.text_input(
                "Text for Failed / Non-OK Records",
                value="FAILED",
                key="multi_failed_text",
                help="Value written into the cell for failed records (error details are added as comments).",
            )
        with c_set2:
            remap_ags10 = st.toggle(
                "🔄 Map AGS 10 to SGR 10",
                value=True,
                key="multi_remap_ags10",
                help="When enabled (default), terminal AGS 10 (Igbesa AGS) is automatically mapped to SGR 10.",
            )

        submit_multi = st.button("💳 Execute Multi-Day Bank Statement Load", type="primary", use_container_width=True)

        if submit_multi:
            if not workbook_file:
                st.error("Please upload the Reconciliation Workbook.")
            else:
                try:
                    with st.spinner(f"Loading {len(plan_configs)} days into workbook blocks..."):
                        output_path, stats = load_multiple_json_to_workbook(
                            workbook_input=workbook_file,
                            items=plan_configs,
                            failed_text=failed_text.strip() or "FAILED",
                            remap_ags10=remap_ags10,
                        )

                    st.success(f"🎉 Successfully loaded **{stats['totalFiles']} days** across workbook blocks!")

                    # Summary Metrics
                    render_metric_cards([
                        ("Files Loaded", stats["totalFiles"], None),
                        ("Total Records", stats["totalJsonRecords"], None),
                        ("Total Matched", stats["totalMatched"], None),
                        ("OK Written", stats["totalOkWritten"], None),
                        ("Failed / Status", stats["totalStatusWritten"], None),
                    ])

                    # Multi-Day Breakdown Table
                    st.markdown("### 📋 Multi-Day Execution Breakdown")
                    breakdown_data = [
                        {
                            "Index": item["index"],
                            "JSON File": item["filename"],
                            "Target Date": item["date"] or "N/A",
                            "Report Block #": item["blockNumber"],
                            "Matched POS": item["matched"],
                            "OK Written": item["okWritten"],
                            "Failed Written": item["statusWritten"],
                            "Total JSON Records": item["jsonRecords"],
                        }
                        for item in stats["items"]
                    ]
                    st.dataframe(breakdown_data, use_container_width=True)

                    # Download Action
                    st.markdown("### 📥 Download Updated Workbook")
                    render_download_button(
                        file_path=output_path,
                        label="📥 Download Multi-Day Reconciled Workbook (.xlsx)",
                        download_filename=f"{workbook_file.name.rsplit('.', 1)[0]}_multi_bank_loaded.xlsx",
                    )

                except Exception as exc:
                    st.error(f"Multi-Day Loader Error: {exc}")

